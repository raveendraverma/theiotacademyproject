document.addEventListener('DOMContentLoaded', () => {
    const customSelect = document.getElementById('customSelect');
    const selectItems = customSelect.querySelector('.select-items');
    const selectSelected = customSelect.querySelector('.select-selected');

    // Toggle the visibility of the custom dropdown
    customSelect.addEventListener('click', () => {
        selectItems.classList.toggle('select-show');
        selectSelected.classList.toggle('select-selected-active');

    });

    let coursename = '';
    selectItems.addEventListener('click', (event) => {
        if (event.target && event.target.matches('div')) {
            selectSelected.textContent = event.target.textContent;
            selectItems.classList.add('select-show');
            coursename = selectSelected.textContent;
            // console.log(coursename);
        }
    });

    document.addEventListener('click', (event) => {
        if (!customSelect.contains(event.target)) {
            selectItems.classList.remove('select-show');

        }
    });

    $(".Newtalktocounsellorfmd").submit(function(e) {
        $('.enqurl_source').val($(location).attr('href'));
        const formUrl = 'https://www.theiotacademy.co/LiveLead/newpopupsubmitsvc';
        const formData = new FormData(this);
        formData.append('coursename', coursename);

        $.ajax({
            type: 'post',
            url: formUrl,
            processData: false,
            contentType: false,
            dataType: 'json',
            data: formData,
            beforeSend: function() {
                $("#enqform-overlay").show();
            },
            success: function(data) {
                if (data.message == "error") {
                    alert(removeTags(data.response));
                    $("#enqform-overlay").hide();
                } else {
                    if (data.message == "success") {
                        $(".Newtalktocounsellorfmd")[0].reset();
                        $("#newpopugvupgform_dv").addClass("d-none");
                        $("#newpopuscssuccesmsg_dv").removeClass("d-none");
                        $(".ensuccess-msg").fadeOut(15000);
                        $("#enqform-overlay").hide();
                    } else {
                        $('.enerror-msg').show();
                        $('.enerror-msg').html(data.response);
                        $(".enerror-msg").fadeOut(15000);
                    }
                }
            }
        });
    });
});
